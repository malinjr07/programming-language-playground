/** Statically Typed Language */

// Primitive Data Type

val b: Byte = 120.toByte() // Integer
val s: Short = 389 // Integer
val i: Int = 467 // Integer
val l: Long = 108 // Integer
val f: Float = 2.652f // Float
val flt: Float = 2.652.toFloat() // Float
val d: Double = 52.6995 // Double Float
val c: Char = 'A' // Character
val flag: Boolean = true // Boolean
val str: String = "New String" // String
val strs: String? = null
val inl: Int? = null

println("Integer Byte b: " + b)

println("Integer Short s: " + s)

println("Integer Int i: " + i)

println("Integer Long l: " + l)

println("Float f: " + f)

println("Double Float d: " + d)

println("Char c: " + c)

println("Boolean flag: " + flag)

println("String str: " + str)

println("Nullable String s: " + strs)

println("Nullable Int inl: " + inl)
