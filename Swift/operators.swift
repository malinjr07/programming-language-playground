import Foundation

var a = 10
var b = 3

// Arithmetic
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)

// Comparison
print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

// Logical
let x = true
let y = false
print(x && y)
print(x || y)
print(!x)

// Bitwise
print(a & b)
print(a | b)
print(a ^ b)
print(~a)
print(a << 1)
print(a >> 1)

// Assignment
a += 5
b *= 2
print(a, b)

// Ternary
print(a > b ? "A greater" : "B greater")
