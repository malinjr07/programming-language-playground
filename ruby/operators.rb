a = 10
b = 3

# Arithmetic
puts a + b
puts a - b
puts a * b
puts a / b
puts a % b
puts a ** b

# Comparison
puts a == b
puts a != b
puts a > b
puts a < b
puts a >= b
puts a <= b

# Logical
x, y = true, false
puts x && y
puts x || y
puts !x

# Bitwise
puts a & b
puts a | b
puts a ^ b
puts ~a
puts a << 1
puts a >> 1

# Assignment
a += 5
b *= 2
puts "#{a}, #{b}"

# Ternary
puts a > b ? "A greater" : "B greater"
