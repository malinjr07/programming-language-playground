a, b = 10, 3

# Arithmetic
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a**b)  # Exponentiation
print(a // b)  # Floor division

# Comparison
print(a == b, a != b, a > b, a < b, a >= b, a <= b)

# Logical
x, y = True, False
print(x and y, x or y, not x)

# Bitwise
print(a & b, a | b, a ^ b, ~a, a << 1, a >> 1)

# Assignment
a += 5
b *= 2
print(a, b)
